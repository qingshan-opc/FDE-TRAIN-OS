import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cc(t: str) -> int:
    return len(re.sub(r"\s+", "", t.strip()))


def ins(text: str, add: str) -> str:
    text = text.strip()
    for suf in ("，对吧。", "，嘛。", "，呢。"):
        if text.endswith(suf):
            return text[: -len(suf)] + "。" + add + suf
    return text.rstrip("。") + "。" + add


def dump(title: str, segments: list[tuple]) -> str:
    lines = [f'title: "{title}"', "segments:"]
    for sid, ppt, text in segments:
        lines += [f'  - id: "{sid}"', "    ppt:"]
        for p in ppt:
            lines.append(f'      - "{p}"')
        lines += ["    text: |", "      " + text, ""]
    return "\n".join(lines).rstrip() + "\n"


