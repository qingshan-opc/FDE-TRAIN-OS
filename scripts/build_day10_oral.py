    total = 0
    for fname, (title, segs) in FILES.items():
        if fname == "day10_s04.yaml":
            continue  # already hand-finished
        out = []
        for sid, ppt, text in segs:
            pads = [
                "听见了吗？这一步听懂了，后面答辩才站得住。",
                "来，对照屏幕，把这一点和全景图上的位置对上。",
                "咱们 FDE 不怕慢，怕假；真通一件，胜过假亮三件。",
                "好，咱们继续往下走。",
            ]
            i = 0
            while cc(text) < 250 and i < len(pads):
                text = ins(text, pads[i])
                i += 1
            if cc(text) < 250:
                text = ins(text, "希望同学们好好听、好好掌握。")
            c = cc(text)
            if not 250 <= c <= 350:
                all_ok = False
                print(f"WARN {fname} {sid}: {c}")
            out.append((sid, ppt, text))
        path = ROOT / "scripts/section_narrations" / fname
        path.write_text(dump(title, out), encoding="utf-8")
        total += len(out)
        print(f"Wrote {fname}: {len(out)} segs")
    # validate s04
    import yaml

    s04 = yaml.safe_load((ROOT / "scripts/section_narrations/day10_s04.yaml").read_text())
    total += len(s04["segments"])
    out_s04 = []
    for seg in s04["segments"]:
        text = seg["text"].strip()
        pads = [
            "听见了吗？这一步听懂了，后面答辩才站得住。",
            "来，对照屏幕，把这一点和全景图上的位置对上。",
            "好，咱们继续往下走。",
        ]
        i = 0
        while cc(text) < 250 and i < len(pads):
            text = ins(text, pads[i])
            i += 1
        out_s04.append((seg["id"], seg["ppt"], text))
    (ROOT / "scripts/section_narrations/day10_s04.yaml").write_text(
        dump(s04["title"], out_s04), encoding="utf-8"
    )
    for sid, _, text in out_s04:
        c = cc(text)
        if not 250 <= c <= 350:
            all_ok = False
            print(f"WARN day10_s04.yaml {sid}: {c}")
    print(f"TOTAL={total} all_ok={all_ok}")


