def oral(day: int, sec_no: int, item: dict[str, Any]) -> str:
    def spoken(text: str) -> str:
        return text.replace("Week1", "第一周").replace("Week2", "第二周").replace("Day", "第")

    points = "\n\n".join(f"「{spoken(p)}」" for p in item["points"])
    return (
        "同学们好，我是你们的老师404。\n\n"
        f"这一节我们只解决一个问题：{spoken(item['concept'])}\n\n"
        f"请记住三件事。\n\n{points}\n\n"
        f"接下来你们要做的不是听懂就算，而是完成这项真实任务：{spoken(item['task'])}\n\n"
        "AI 可以生成文件、代码和建议，但批准权不能交出去。你要看实际文件、亲手验证，再决定通过还是返工。\n\n"
        "同学们，本节先到这里。"
    )


def lesson_md(day: int, sec_no: int, item: dict[str, Any]) -> str:
    bullets = "\n".join(f"- {p}" for p in item["points"])
    return f"""# 第 {sec_no} 节 · {item['title']}（{item['minutes']}′ · {item['form']}）

> {item['concept']}

## 教学目标

- 学员能用自己的项目解释本节概念，而不是背技术名词；
- 学员能向指定岗位下达一句清楚的任务，并说出验收口径；
- 学员只根据真实文件和运行证据批准交付。

## 讲授要点

{bullets}

**本节岗位**：{item['actor']}

**本节产出**：{item['outcome']}

**本周共同边界**：{SHARED_BOUNDARY}

## 🎬 口播稿（短讲版）

{oral(day, sec_no, item)}

## 常见懵点（导师备用）

- “能不能让一个 Agent 一次做完？”→ 可以很快看到结果，但会失去岗位交接、状态变化和验收过程，这正是本课要学的部分。
- “我不懂代码怎么验收？”→ 先按页面、文件、请求响应和数据变化验收；让工程师解释原因，不要求学员先会写代码。
- “Agent 说完成了是不是就算完成？”→ 不算。只有实际文件存在、验证真实执行且学员明确批准，状态才从 REVIEW 进入 APPROVED。
"""


