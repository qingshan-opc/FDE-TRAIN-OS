def write_day(day: int, data: dict[str, Any]) -> None:
    day_dir = BC / f"day-{day:02d}"
    (day_dir / "README.md").write_text(readme_md(day, data), encoding="utf-8")
    yaml_text = yaml.safe_dump(day_yaml(day, data), allow_unicode=True, sort_keys=False, width=120)
    (day_dir / "day.yaml").write_text(yaml_text, encoding="utf-8")
    for i, item in enumerate(data["sections"], start=1):
        sec_dir = day_dir / item["dir"]
        sec_dir.mkdir(parents=True, exist_ok=True)
        (sec_dir / "lesson.md").write_text(lesson_md(day, i, item), encoding="utf-8")
        (sec_dir / "practice.md").write_text(practice_md(i, item), encoding="utf-8")


def main() -> None:
    for day, data in DAYS.items():
        write_day(day, data)
        print(f"day-{day:02d}: {data['title']} · {len(data['sections'])} sections")


if __name__ == "__main__":
    main()
