def _ppt_for(seg_id: str, title: str) -> list[str]:
    slug = seg_id.split("-", 1)[-1].upper().replace("-", " ")
    return [f"眉题：{seg_id.split('-')[0]} {slug}", title]


def write_yaml(key: str, data: dict) -> None:
    segs = []
    for seg_id, text in data["segments"]:
        cleaned = "\n".join(line.strip() for line in text.strip().splitlines() if line.strip()) + "\n"
        cleaned = _pad_segment(key, seg_id, cleaned)
        segs.append({"id": seg_id, "ppt": _ppt_for(seg_id, data["title"]), "text": cleaned})
    out = {"title": data["title"], "segments": segs}
    path = YAML_DIR / f"day07_{key}.yaml"
    path.write_text(yaml.dump(out, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    chars = sum(len(s["text"]) for s in segs)
    print(f"wrote {path.name} · {len(segs)} segs · {chars} chars")


def main() -> None:
    for key, data in SECTIONS.items():
        write_yaml(key, data)
    subprocess.run(
        [sys.executable, str(ROOT / "scripts/sync_bootcamp_section_from_yaml.py"), "--from-day", "7", "--to-day", "7"],
        check=True,
        cwd=ROOT,
    )


if __name__ == "__main__":
    main()
